a = 5   # binary: 0101
b = 3   # binary: 0011
print(a & b)   # 1
print(a | b)   # 7
print(a ^ b)   # 6
print(~b)      # -4
print(a << b)  # 40
print(a >> b)  # a = 10

b = -10


